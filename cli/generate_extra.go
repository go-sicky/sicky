func generateProtoFile(args []string) int {
	fs, gf, err := parseGenerateFlags("generate proto", args)
	if err != nil {
		fmt.Fprintf(os.Stderr, "sicky generate proto: %s\n", err.Error())

		return 1
	}

	if fs.NArg() < 1 {
		fmt.Fprintln(os.Stderr, "sicky generate proto: missing proto name")

		return 1
	}

	name := strings.ToLower(fs.Arg(0))
	dir := gf.output
	if dir == "" {
		dir = "proto"
	}

	svc := exportName(name)
	content := "syntax = \"proto3\";\n\npackage " + name + ";\n\noption go_package = \"./;pb\";\n\n" +
		"service " + svc + " {\n  rpc Ping (PingRequest) returns (PingReply);\n}\n\n" +
		"message PingRequest {\n  string message = 1;\n}\n\n" +
		"message PingReply {\n  string message = 1;\n}\n"

	return writeGuard(filepath.Join(dir, name+".proto"), content, gf, "proto")
}

func generateConfigFile(args []string) int {
	fs, gf, err := parseGenerateFlags("generate config", args)
	if err != nil {
		fmt.Fprintf(os.Stderr, "sicky generate config: %s\n", err.Error())

		return 1
	}

	_ = fs
	nc := &newContext{
		Name:           detectProjectName(),
		Module:         detectModule(),
		Type:           "standard",
		Servers:        []string{"fiber", "grpc"},
		Registry:       "local",
		Tracer:         "none",
		DockerRegistry: "docker.io",
	}

	nc.AppName = nc.Name + ".example.sicky"
	nc.ExportedName = exportName(nc.Name)
	if err := normalizeNewContext(nc); err != nil {
		fmt.Fprintf(os.Stderr, "sicky generate config: %s\n", err.Error())

		return 1
	}

	content, err := renderProjectTemplate("template/project/standard/config.json.gotmpl", nc)
	if err != nil {
		fmt.Fprintf(os.Stderr, "sicky generate config: %s\n", err.Error())

		return 1
	}

	outputPath := "config.json"
	if gf.output != "" {
		outputPath = filepath.Join(gf.output, "config.json")
	}

	return writeGuard(outputPath, content, gf, "config")
}

func generateDockerFiles(args []string) int {
	_, gf, err := parseGenerateFlags("generate docker", args)
	if err != nil {
		fmt.Fprintf(os.Stderr, "sicky generate docker: %s\n", err.Error())

		return 1
	}

	nc := &newContext{
		Name:           detectProjectName(),
		Module:         detectModule(),
		DockerRegistry: "docker.io",
	}

	nc.AppName = nc.Name + ".example.sicky"
	nc.ExportedName = exportName(nc.Name)
	dockerfile, err := renderProjectTemplate("template/project/shared/Dockerfile.gotmpl", nc)
	if err != nil {
		fmt.Fprintf(os.Stderr, "sicky generate docker: %s\n", err.Error())

		return 1
	}

	ignore, err := renderProjectTemplate("template/project/shared/dockerignore.gotmpl", nc)
	if err != nil {
		fmt.Fprintf(os.Stderr, "sicky generate docker: %s\n", err.Error())

		return 1
	}

	dir := gf.output
	if dir == "" {
		dir = "."
	}

	if rc := writeGuard(filepath.Join(dir, "Dockerfile"), dockerfile, gf, "docker"); rc != 0 {
		return rc
	}

	return writeGuard(filepath.Join(dir, ".dockerignore"), ignore, gf, "docker")
}

func generateK8sFiles(args []string) int {
	fs, gf, err := parseGenerateFlags("generate k8s", args)
	if err != nil {
		fmt.Fprintf(os.Stderr, "sicky generate k8s: %s\n", err.Error())

		return 1
	}

	name := detectProjectName()
	if fs.NArg() >= 1 {
		name = fs.Arg(0)
	}

	dir := gf.output
	if dir == "" {
		dir = "deploy"
	}

	deploy := "apiVersion: apps/v1\nkind: Deployment\nmetadata:\n  name: " + name + "\n" +
		"spec:\n  replicas: 2\n  selector:\n    matchLabels:\n      app: " + name + "\n" +
		"  template:\n    metadata:\n      labels:\n        app: " + name + "\n" +
		"    spec:\n      containers:\n      - name: svc\n" +
		"        image: " + name + ":latest\n        ports:\n        - containerPort: 3000\n" +
		"        - containerPort: 8888\n"
	svc := "apiVersion: v1\nkind: Service\nmetadata:\n  name: " + name + "\n" +
		"spec:\n  selector:\n    app: " + name + "\n  ports:\n  - name: http\n    port: 3000\n" +
		"  - name: manager\n    port: 8888\n"
	if rc := writeGuard(filepath.Join(dir, "deployment.yaml"), deploy, gf, "k8s"); rc != 0 {
		return rc
	}

	return writeGuard(filepath.Join(dir, "service.yaml"), svc, gf, "k8s")
}

