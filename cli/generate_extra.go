func generateServerStub(args []string) int {
	fs, gf, err := parseGenerateFlags("generate server", args)
	if err != nil {
		fmt.Fprintf(os.Stderr, "sicky generate server: %s\n", err.Error())

		return 1
	}

	if fs.NArg() < 1 {
		fmt.Fprintln(os.Stderr, "sicky generate server: missing server type")
		fmt.Fprintf(os.Stderr, "Valid: %s\n", strings.Join(extraServers, ","))

		return 1
	}

	kind := strings.ToLower(fs.Arg(0))
	ok := false
	for _, v := range extraServers {
		if kind == v || (kind == "ws" && v == "websocket") {
			kind = v
			ok = true
		}
	}

	if !ok {
		fmt.Fprintf(os.Stderr, "sicky generate server: unknown server %q (valid: %s)\n", fs.Arg(0), strings.Join(extraServers, ","))

		return 1
	}

	name := kind
	if fs.NArg() >= 2 {
		name = fs.Arg(1)
	}

	dir := gf.output
	if dir == "" {
		dir = "internal/server"
	}

	content := "// Package server wires a " + kind + " server instance.\n" +
		"// Generated by `sicky generate server " + kind + "`. TODO: fill addresses from config.\n" +
		"package server\n\n" +
		"// " + exportName(name) + "Kind identifies this server wiring.\n" +
		"const " + exportName(name) + "Kind = \"" + kind + "\"\n"

	return writeGuard(filepath.Join(dir, name+".go"), content, gf, "server")
}

